package com.example.cantina;

public class Aluno {
    private String idAluno;
    private String nome;
    private String email;
    private String turma;
    public Aluno() {}
    public String getIdAluno() { return idAluno; }
    public void setIdAluno(String valor) { idAluno=valor; }
    public String getNome() { return nome; }
    public void setNome(String valor) { nome=valor; }
    public String getEmail() { return email; }
    public void setEmail(String valor) { email=valor; }
    public String getTurma() { return turma; }
    public void setTurma(String valor) { turma=valor; }
}
