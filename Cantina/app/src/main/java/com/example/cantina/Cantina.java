package com.example.cantina;

public class Cantina {
    private String idCantina;
    private String nome;
    private String email;
    public Cantina() {}
    public String getIdCantina() { return idCantina; }
    public void setIdCantina(String valor) { idCantina=valor; }
    public String getNome() { return nome; }
    public void setNome(String valor) { nome=valor; }
    public String getEmail() { return email; }
    public void setEmail(String valor) { email=valor; }
}
