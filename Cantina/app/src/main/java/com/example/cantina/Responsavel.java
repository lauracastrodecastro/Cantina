package com.example.cantina;

public class Responsavel {
    private String idResponsavel;
    private String nome;
    private String email;
    public Responsavel() {}
    public String getIdResponsavel() { return idResponsavel; }
    public void setIdResponsavel(String valor) { idResponsavel=valor; }
    public String getNome() { return nome; }
    public void setNome(String valor) { nome=valor; }
    public String getEmail() { return email; }
    public void setEmail(String valor) { email=valor; }
}
